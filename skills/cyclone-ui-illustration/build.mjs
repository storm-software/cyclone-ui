#!/usr/bin/env node
/**
 * Builds an illustration: `node build.mjs <name>.js [--out <dir>] [--import <specifier>]`
 * writes, in the output folder (the working directory by default):
 *
 *   illustration-<name>.html         the bench: bench.html with kernel.js and the illustration in its two slots, nothing else changed
 *   illustration-<name>.svg          the rest pose as a static image, light or dark with the colour scheme (and a t_light / t_dark ancestor when inlined)
 *   illustration-<name>.light.svg    the same, pinned light
 *   illustration-<name>.dark.svg     the same, pinned dark
 *   <Name>Illustration.tsx           a React component for a Cyclone UI app: react-native-svg, themed with Cyclone UI tokens, web and native
 *
 * and prints where each is. The static images come from the same kernel as the
 * bench, run in Node: the illustration is mounted with no page, every motion
 * is landed, and its nodes are written out. `--import` is where the component
 * takes `createIllustration` from (default `@cyclone-ui/illustrations/create-illustration`).
 *
 * Adapted from Hairline's build.mjs (https://github.com/lucasmarkes/hairline,
 * © 2026 Lucas Marques, MIT License).
 */
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import vm from "node:vm";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const unix = (s) => s.replace(/\r\n/g, "\n");
export const IMPORT = "@cyclone-ui/illustrations/create-illustration";
/** The declaration at the end of an illustration file. */
const DECLARATION = /\billustration\s*\(\s*\{([\s\S]*?)\}\s*\)\s*;?\s*$/;

export const kernelText = () => unix(readFileSync(here("./kernel.js"), "utf8")).trimEnd();

/** The page for an illustration's source. The replacements are functions so `$&` in the kernel or the illustration is pasted as it is. */
export function assemble(source) {
  return unix(readFileSync(here("./bench.html"), "utf8"))
    .replace("/*KERNEL*/", () => `\n${kernelText()}\n`)
    .replace("/*ILLUSTRATION*/", () => `\n${unix(source).trim()}\n`);
}

/** The illustration's name, read from its declaration: the last illustration({ … }) call, as validate.mjs reads it. */
export function nameOf(source) {
  const call = [...source.matchAll(/\billustration\s*\(\s*\{/g)].at(-1);
  return call ? /\bname:\s*["'`]([a-z][a-z0-9-]*)["'`]/.exec(source.slice(call.index))?.[1] ?? null : null;
}

/** `deploy-locks` → `DeployLocks`. */
export const pascal = (name) => name.split("-").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");

/**
 * The kernel and the illustration, run in a fresh Node context with no page:
 * `{ HL, def }`, the def being what the illustration declared. Throws what the
 * illustration throws.
 */
export function load(source) {
  const context = vm.createContext({ performance, setTimeout, clearTimeout, queueMicrotask, console });
  vm.runInContext(kernelText(), context, { filename: "kernel.js" });
  let def = null;
  context.illustration = (d) => { def = d; };
  vm.runInContext(unix(source), context, { filename: "illustration.js" });
  if (!def) throw new Error("the illustration never called illustration({ … })");
  return { HL: context.HL, def };
}

/** The three static images of the rest pose, at the slider's middle: auto, light and dark. */
export function statics(source) {
  const { HL, def } = load(source), value = HL.level(def.range, 0.5);
  return { auto: HL.snapshot(def, value, "auto"), light: HL.snapshot(def, value, "light"), dark: HL.snapshot(def, value, "dark") };
}

/**
 * The React component: the illustration's code as it is, with HL taken from
 * the package and its declaration handed to createIllustration. The code is
 * plain JavaScript, checked by validate.mjs and look.mjs rather than by
 * TypeScript, so the file opts out of type checking and linting.
 */
export function component(source, from = IMPORT) {
  const name = nameOf(source) ?? "illustration", Name = `${pascal(name)}Illustration`;
  const body = unix(source).trim().replace(DECLARATION, (_, inner) =>
    `export const ${Name}: IllustrationComponent = createIllustration({${inner}});`);
  return `/* eslint-disable */
// @ts-nocheck -- plain JavaScript from ${name}.js, checked by the cyclone-ui-illustration skill's validate.mjs and look.mjs
"use client";

/*
 * ${Name}: generated by the cyclone-ui-illustration skill from ${name}.js.
 * Change ${name}.js and run build.mjs again rather than editing this file.
 *
 * Built on the Hairline engine (https://github.com/lucasmarkes/hairline) by
 * Lucas Marques, MIT License.
 */

import type { IllustrationComponent } from "${from}";
import { createIllustration, HL } from "${from}";

${body}
`;
}

/** Whether two resolved paths are one file. Windows paths ignore case, and the drive letter's case can differ between the two. */
export const same = (a, b, platform = process.platform) => platform === "win32" ? a.toLowerCase() === b.toLowerCase() : a === b;

/* The skill is often installed as a symlink, so the path Node was given is resolved before it is compared. */
if (process.argv[1] && same(realpathSync(process.argv[1]), realpathSync(here("./build.mjs")))) {
  let args;
  try {
    args = parseArgs({ allowPositionals: true, options: { out: { type: "string" }, import: { type: "string" } } });
  } catch (e) {
    console.error(`${e.message}\nusage: node build.mjs <name>.js [--out <dir>] [--import <specifier>]`);
    process.exit(2);
  }
  const { positionals: [src], values } = args;
  if (!src) {
    console.error("usage: node build.mjs <name>.js [--out <dir>] [--import <specifier>]");
    process.exit(2);
  }
  const source = readFileSync(src, "utf8"), name = nameOf(source) ?? "illustration", out = resolve(values.out ?? ".");
  mkdirSync(out, { recursive: true });
  const write = (file, text) => { const path = join(out, file); writeFileSync(path, text); console.log(path); };
  write(`illustration-${name}.html`, assemble(source));
  write(`${pascal(name)}Illustration.tsx`, component(source, values.import ?? IMPORT));
  try {
    const svg = statics(source);
    write(`illustration-${name}.svg`, svg.auto);
    write(`illustration-${name}.light.svg`, svg.light);
    write(`illustration-${name}.dark.svg`, svg.dark);
  } catch (e) {
    console.error(`static: the illustration does not draw without a page: ${e.message}. It must: the component renders it on the server and on native. Fix it, then build again.`);
    process.exit(1);
  }
}
