/**
 * Check for updates to the application dependencies.
 *
 * @remarks
 * This function is used to check for updates to the application dependencies. It can be used in the CLI update command to ensure that all necessary dependencies are up-to-date.
 *
 *
 * @param options - The options for the `checkForUpdates` function. Currently,
 *   there are no options available, but this parameter is included for future
 *   extensibility.
 * @returns A promise that resolves when the check for updates is complete or
 *   undefined if the check was not performed.
 *
 */
export async function checkForUpdates(
  options: CheckForUpdatesOptions = {}
): Promise<CheckForUpdatesResult> {
  if (!options.force && !(await isCheckForUpdatesRequired())) {
    return {
      latestVersion: "0.47.125",
      currentVersion: "0.47.125",
      isUpToDate: true,
      isError: false
    };
  }

  try {
    const pkg = await fetchNpmPackage("@powerlines/cli");

    return {
      latestVersion: pkg?.version || "0.47.125",
      currentVersion: "0.47.125",
      isUpToDate: pkg ? "0.47.125" === pkg.version : true,
      package: pkg,
      isError: false
    };
  } catch (err) {
    return {
      isError: true,
      error: err instanceof Error ? err : new Error(String(err))
    };
  }
}

/**
 * A helper function that verifies if a check for updates is required.
 *
 * @remarks
 * This function is used to determine if a check for updates is required based on the last time a check was performed. It can be used in the CLI update command to avoid unnecessary checks for updates if one was recently performed. The function checks for the existence of a "update-check.json" file in the data directory, which contains a timestamp of the last check for updates. If the file does not exist or if the timestamp is older than a specified stale time, the function will return true, indicating that a check for updates is required. Otherwise, it will return false.
 *
 *
 * @returns A promise that resolves to a boolean indicating whether a check for
 *   updates is required.
 *
 */
export async function isCheckForUpdatesRequired() {
  if (!isInteractive || isCI || env.SKIP_UPDATE_CHECK) {
    return false;
  }

  const filePath = join(paths.data, "update-check.json");
  if (existsSync(filePath)) {
    const file: { timestamp: number } = JSON.parse(
      await readFile(filePath, "utf8")
    );
    if (!file.timestamp) {
      await updateVersionCheckFile();
      return true;
    } else if (new Date().getTime() - file.timestamp < 129600000) {
      return false;
    }
  } else {
    await updateVersionCheckFile();
    return true;
  }
}

/**
 * A helper function that updates the version check file.
 *
 * @remarks
 * This function is used to update the version check file with the current timestamp. It can be used in the CLI update command to record the last time a check for updates was performed. The function writes a "update-check.json" file in the data directory, which contains a timestamp of the last check for updates.
 *
 *
 * @returns A promise that resolves to a boolean indicating whether a check for
 *   updates is required.
 *
 */
export async function updateVersionCheckFile(): Promise<void> {
  if (!existsSync(paths.data)) {
    await mkdir(paths.data, { recursive: true });
  }
  await writeFile(
    join(paths.data, "update-check.json"),
    JSON.stringify({ timestamp: new Date().getTime() }),
    "utf8"
  );
}

/**
 * Run update processing for the Powerlines application.
 */
export async function executeUpdate() {
  if (await isCheckForUpdatesRequired()) {
    const spinner = createSpinner({
      message: "Checking for updates..."
    }).start();
    const result = await checkForUpdates({ force: true });
    if ((result as CheckForUpdatesErrorResult)?.isError) {
      spinner.error(
        `An error occurred while checking for Powerlines application updates. Please try again later - if the problem persists, please contact support.`
      );
      debug((result as CheckForUpdatesErrorResult).error);
    } else if (!(result as CheckForUpdatesSuccessResult)?.isUpToDate) {
      spinner.stop();
      info(
        `A new version of Powerlines is available: ${red(`v${(result as CheckForUpdatesSuccessResult).currentVersion}`)} ${textColors.body.tertiary("➜")} ${green(`v${(result as CheckForUpdatesSuccessResult).latestVersion}`)}${(result as CheckForUpdatesSuccessResult).package?.date ? textColors.body.tertiary(` (updated on ${(result as CheckForUpdatesSuccessResult).package?.date})`) : ""}`
      );

      try {
        await update();
        spinner.success(
          "Update successful! Please restart the application to apply the update."
        );

        writeLine("");
        help(
          `The changelog for this release can be viewed by running the ${inlineCode("powerlines changelog")} command.`
        );

        writeLine("");
        writeLine("Press any key to exit the application...");

        await waitForKeyPress();
        return;
      } catch (err) {
        spinner.error(
          `An error occurred while updating Powerlines to v${(result as CheckForUpdatesSuccessResult).latestVersion}. Please try again later - if the problem persists, please contact support.`
        );
        debug(err);
      }
    } else {
      spinner.success("Currently running the latest version of Powerlines.");
      writeLine("");
    }
  }
}
