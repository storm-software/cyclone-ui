/**
 * Locate the package.json file currently being used by the command-line/workspace.
 *
 * @remarks
 * This function is used to determine the package.json file currently being used by the command-line/workspace. It can be used in the CLI update command to check if the application is using npm, yarn, or another package manager.
 *
 *
 * @param options - The options for the `locatePackageJson` function. Currently,
 *   there are no options available, but this parameter is included for future
 *   extensibility.
 * @returns A promise that resolves to the package.json file currently being
 *   used by the command-line/workspace as a string.
 *
 */
export async function locatePackageJson(
  options: LocatePackageJsonOptions = {}
): Promise<string | undefined> {
  let currentPath: string = options.cwd ?? process.cwd();
  let parentPath = resolve(currentPath, "..");

  while (
    parentPath !== currentPath &&
    currentPath !== homePath &&
    currentPath !== tempPath
  ) {
    const packageJsonPath = join(currentPath, "package.json");
    if (existsSync(packageJsonPath)) {
      if (options.isDependencyRequired) {
        const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
        if (
          Object.keys(packageJson.dependencies || {})
            .concat(Object.keys(packageJson.devDependencies || {}))
            .concat(Object.keys(packageJson.peerDependencies || {}))
            .concat(Object.keys(packageJson.optionalDependencies || {}))
            .some(
              dep =>
                dep === "@powerlines/cli" || dep.startsWith("@powerlines/cli@")
            )
        ) {
          return packageJsonPath;
        }
      } else {
        return packageJsonPath;
      }
    } else {
      currentPath = parentPath;
      parentPath = resolve(currentPath, "..");
    }
  }

  return undefined;
}

