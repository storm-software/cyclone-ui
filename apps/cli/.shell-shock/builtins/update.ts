/**
 * Get the package manager currently being used by the command-line/workspace.
 *
 * @remarks
 * This function is used to determine the package manager currently being used by the command-line/workspace. It can be used in the CLI update command to check if the application is using npm, yarn, or another package manager.
 *
 *
 * @param options - The options for the `getPackageManager` function. Currently,
 *   there are no options available, but this parameter is included for future
 *   extensibility.
 * @returns A promise that resolves to the package manager currently being used
 *   by the command-line/workspace as a string.
 *
 */
export async function getPackageManager(
  options: GetPackageManagerOptions = {}
): Promise<"npm" | "yarn" | "deno" | "pnpm" | "bun"> {
  const userAgent: string = process.env.npm_config_user_agent ?? "";
  const execPath: string = process.env.npm_execpath ?? "";

  if (userAgent.startsWith("yarn") || execPath.includes("yarn")) {
    return "yarn";
  } else if (userAgent.startsWith("pnpm") || execPath.includes("pnpm")) {
    return "pnpm";
  } else if (
    userAgent.startsWith("bun") ||
    execPath.includes("bun") ||
    process.versions.bun
  ) {
    return "bun";
  } else {
    const lockfilePath = locateLockfile(options);

    if (lockfilePath === "yarn.lock") {
      return "yarn";
    } else if (
      lockfilePath === "deno.lock" ||
      lockfilePath === "deno.json" ||
      lockfilePath === "deno.jsonc"
    ) {
      return "deno";
    } else if (
      lockfilePath === "pnpm-lock.yaml" ||
      lockfilePath === "pnpm-workspace.yaml"
    ) {
      return "pnpm";
    } else if (lockfilePath === "bun.lock" || lockfilePath === "bun.lockb") {
      return "bun";
    } else {
      const packageJsonPath = await locatePackageJson(options);
      if (packageJsonPath && existsSync(packageJsonPath)) {
        const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
        if (
          packageJson.devEngines?.packageManager?.name &&
          typeof packageJson.devEngines.packageManager.name === "string" &&
          ["npm", "yarn", "pnpm", "deno", "bun"].includes(
            packageJson.devEngines.packageManager.name
          )
        ) {
          return packageJson.devEngines.packageManager.name;
        }

        const dependencies = {
          ...packageJson.dependencies,
          ...packageJson.devDependencies,
          ...packageJson.peerDependencies,
          ...packageJson.optionalDependencies
        };
        if (
          Object.keys(dependencies).some(
            dep =>
              dep === "yarn" ||
              dep.startsWith("yarn@") ||
              dep === "yarnpkg" ||
              dep.startsWith("yarnpkg@")
          )
        ) {
          return "yarn";
        } else if (
          Object.keys(dependencies).some(
            dep => dep === "bun" || dep.startsWith("bun@")
          )
        ) {
          return "bun";
        } else if (
          Object.keys(dependencies).some(
            dep => dep === "pnpm" || dep.startsWith("pnpm@")
          )
        ) {
          return "pnpm";
        } else if (
          Object.keys(dependencies).some(
            dep => dep === "deno" || dep.startsWith("deno@")
          )
        ) {
          return "deno";
        }
      }

      return "npm";
    }
  }
}

