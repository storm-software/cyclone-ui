/**
 * Write the Powerlines command-line interface application banner for the Completions - Fish Configuration command to the console.
 *
 * @param sleepTimeoutMs - The amount of time in milliseconds to sleep before
 *   displaying the banner. This can be used to create a delay before the banner
 *   is shown, allowing for any necessary setup or initialization to occur
 *   first. The default value is 500 milliseconds.
 */
export async function showBanner(sleepTimeoutMs: number = 500) {
  if (
    useMeta().get("is-banner-displayed") ||
    hasFlag("no-banner") ||
    hasFlag("hide-banner") ||
    isMinimal
  ) {
    return;
  }

  useMeta().set("is-banner-displayed", true);

  writeLine("");

  writeLine(
    borderColors.banner.outline.primary("┏") +
      borderColors.banner.outline.primary("━".repeat(6)) +
      " " +
      textColors.banner.header.primary("⬤") +
      " " +
      borderColors.banner.outline.primary("━") +
      " " +
      bold(textColors.banner.header.primary("Powerlines CLI v0.47.125")) +
      " " +
      borderColors.banner.outline.primary(
        "━".repeat(Math.max(getTerminalSize().columns - 38, 0))
      ) +
      borderColors.banner.outline.primary("┓"),
    { consoleFn: console.log }
  );

  const title =
    Math.max(...TITLE_LINES.map(line => stripAnsi(line).length)) >
    Math.max(getTerminalSize().columns + 30, 20)
      ? "Powerlines"
      : `\n${TITLE_LINES.join("\n")}\n`;

  splitText(title, Math.max(getTerminalSize().columns - 30, 20)).forEach(
    line => {
      writeLine(
        borderColors.banner.outline.primary("┃") +
          " ".repeat(
            Math.max(
              Math.floor(
                (getTerminalSize().columns - (stripAnsi(line).length + 2)) / 2
              ),
              0
            )
          ) +
          bold(textColors.banner.title.primary(line)) +
          " ".repeat(
            Math.max(
              Math.ceil(
                (getTerminalSize().columns - (stripAnsi(line).length + 2)) / 2
              ),
              0
            )
          ) +
          borderColors.banner.outline.primary("┃"),
        { consoleFn: console.log }
      );
    }
  );
  writeLine(
    borderColors.banner.outline.primary("┃") +
      " ".repeat(
        Math.max(
          Math.floor(
            (getTerminalSize().columns -
              (stripAnsi("Completions - Fish Configuration").length + 2)) /
              2
          ),
          0
        )
      ) +
      bold(
        textColors.banner.command.primary("Completions - Fish Configuration")
      ) +
      " ".repeat(
        Math.max(
          Math.ceil(
            (getTerminalSize().columns -
              (stripAnsi("Completions - Fish Configuration").length + 2)) /
              2
          ),
          0
        )
      ) +
      borderColors.banner.outline.primary("┃"),
    { consoleFn: console.log }
  );

  splitText(
    bold(
      textColors.banner.description.primary(
        `Update the current system\'s Fish shell configuration to include completions for the Powerlines command-line interface.`
      )
    ),
    Math.max(
      60 > getTerminalSize().columns / 2
        ? getTerminalSize().columns - 6
        : getTerminalSize().columns - 30,
      20
    )
  ).forEach(line => {
    writeLine(
      borderColors.banner.outline.primary("┃") +
        " ".repeat(
          Math.max(
            Math.floor(
              (getTerminalSize().columns - (stripAnsi(line).length + 2)) / 2
            ),
            0
          )
        ) +
        textColors.banner.description.primary(line) +
        " ".repeat(
          Math.max(
            Math.ceil(
              (getTerminalSize().columns - (stripAnsi(line).length + 2)) / 2
            ),
            0
          )
        ) +
        borderColors.banner.outline.primary("┃"),
      { consoleFn: console.log }
    );
  });

  writeLine(
    borderColors.banner.outline.primary("┃") +
      " ".repeat(Math.max(getTerminalSize().columns - 2, 0)) +
      borderColors.banner.outline.primary("┃"),
    { consoleFn: console.log }
  );

  writeLine(
    borderColors.banner.outline.primary("┗") +
      borderColors.banner.outline.primary(
        "━".repeat(Math.max(getTerminalSize().columns - 35, 0))
      ) +
      " " +
      bold(textColors.banner.footer.primary("https://stormsoftware.com")) +
      " " +
      borderColors.banner.outline.primary("━".repeat(6)) +
      borderColors.banner.outline.primary("┛"),
    { consoleFn: console.log }
  );

  writeLine("");

  if (isInteractive && !isHelp()) {
    await sleep(sleepTimeoutMs);
  }
}
