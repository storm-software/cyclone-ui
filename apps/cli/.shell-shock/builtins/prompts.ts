/**
 * Configuration options for creating a numeric prompt
 */
interface NumberPromptConfig extends PromptConfig<number> {
  /**
   * Whether the prompt should accept floating point numbers
   */
  isFloat?: boolean;

  /**
   * The number of decimal places to round the input to, defaults to 2
   */
  precision?: number;

  /**
   * The increment value for the number prompt, defaults to 1
   */
  increment?: number;

  /**
   * The minimum value for the number prompt, defaults to -Infinity
   */
  min?: number;

  /**
   * The maximum value for the number prompt, defaults to Infinity
   */
  max?: number;
}

/**
 * A prompt for selecting a number input
 */
class NumberPrompt extends Prompt<number> {
  #isInvalid: boolean = false;

  protected override initialValue: number = 0;
  protected override defaultErrorMessage: string =
    "A valid numeric value must be provided";
  protected isFloat: boolean = false;
  protected precision: number = 2;
  protected increment: number = 1;
  protected min: number = Number.NEGATIVE_INFINITY;
  protected max: number = Number.POSITIVE_INFINITY;

  constructor(config: NumberPromptConfig) {
    super(config);

    if (config.initialValue) {
      this.initialValue = config.initialValue;
    }

    this.isFloat = !!config.isFloat;
    if (config.precision !== undefined) {
      this.precision = config.precision;
    }
    if (config.increment !== undefined) {
      this.increment = config.increment;
    }
    if (config.min !== undefined) {
      this.min = config.min;
    }
    if (config.max !== undefined) {
      this.max = config.max;
    }

    if (config.parse) {
      this.parse = config.parse.bind(this);
    } else {
      const parse = (value: string) =>
        this.isFloat
          ? Math.round(
              Math.pow(10, this.precision) * Number.parseFloat(value)
            ) / Math.pow(10, this.precision)
          : Number.parseInt(value);
      this.parse = parse.bind(this);
    }

    if (config.validate) {
      this.validate = config.validate.bind(this);
    } else {
      const validate = (value: number) =>
        !Number.isNaN(value) && value >= this.min && value <= this.max;
      this.validate = validate.bind(this);
    }

    this.changeValue(this.initialValue);

    this.cursor = 0;
    this.sync();
    this.last();
  }

  /**
   * A method to handle key press events and determine the corresponding action
   *
   * @param char
   * @param key
   */
  protected override onKeyPress(char: string, key: Key) {
    const action = this.getAction(key);
    if (action && typeof (this as any)[action] === "function") {
      return (this as any)[action]();
    }

    if (
      (char !== "-" || (char === "-" && this.cursor !== 0)) &&
      !(char === "." && this.isFloat) &&
      !/[0-9]/.test(char)
    ) {
      return this.bell();
    }

    const displayValue = `${this.displayValue.slice(
      0,
      this.cursor
    )}${char}${this.displayValue.slice(this.cursor)}`;

    let value = this.parse(displayValue);
    if (!Number.isNaN(value)) {
      value = Math.min(value, this.max);
      if (value > this.max) {
        value = this.max;
      }
      if (value < this.min) {
        value = this.min;
      }
    }

    this.changeValue(value);
    this.sync();
  }

  /**
   * A method to handle changes in the prompt value
   *
   * @param previousValue
   */
  protected override onChange(previousValue: number) {
    this.#isInvalid = false;
    this.cursor = this.displayValue.slice(0, this.cursor).length + 1;
  }

  /**
   * A method to validate the prompt input
   */
  protected override async checkValidations() {
    await super.checkValidations(this.value);
    this.#isInvalid = this.isError;
  }

  /**
   * A method to move the cursor to the end of the input
   */
  protected next() {
    this.changeValue(this.initialValue);
    this.sync();
  }

  /**
   * A method to move the cursor to the up
   */
  protected up() {
    let value = this.value;
    if (this.isPlaceholder) {
      value = this.min < 0 ? 0 : this.min;
    } else if (value >= this.max) {
      return this.bell();
    }

    this.changeValue(value + this.increment);

    this.sync();
    this.last();
  }

  /**
   * A method to move the cursor to the down
   */
  protected down() {
    let value = this.value;
    if (this.isPlaceholder) {
      value = this.min < 0 ? 0 : this.min;
    } else if (value <= this.min) {
      return this.bell();
    }

    this.changeValue(value === this.min ? this.min : value - this.increment);
    this.sync();
    this.last();
  }

  /**
   * A method to move the cursor to the left
   */
  protected left() {
    if (this.cursor <= 0) {
      return this.bell();
    }

    this.moveCursor(-1);
    this.sync();
  }

  /**
   * A method to move the cursor to the right
   */
  protected right() {
    if (this.cursor >= this.displayValue.length) {
      return this.bell();
    }

    this.moveCursor(1);
    this.sync();
  }

  /**
   * A method to move the cursor to the start
   */
  protected first() {
    this.cursor = 0;
    this.sync();
  }

  /**
   * A method to move the cursor to the end
   */
  protected last() {
    this.cursor = this.displayValue.length;
    this.sync();
  }

  /**
   * A method to render the prompt
   */
  protected override onRender(): string {
    return this.isPlaceholder
      ? textColors.prompt.input.disabled(this.displayValue)
      : this.#isInvalid
        ? textColors.prompt.input.error(this.displayValue)
        : this.isSubmitted
          ? textColors.prompt.input.submitted(this.displayValue)
          : this.isCancelled
            ? textColors.prompt.input.cancelled(this.displayValue)
            : bold(textColors.prompt.input.active(this.displayValue));
  }
}

