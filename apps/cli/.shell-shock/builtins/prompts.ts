/**
 * A prompt for selecting an option from a list
 */
class SelectPrompt<TValue = string> extends Prompt<TValue> {
  protected override initialValue: TValue;
  protected optionsPerPage: number = 8;
  protected options: PromptOption<TValue>[] = [];
  protected override cursorHidden: boolean = true;

  constructor(config: SelectPromptConfig<TValue>) {
    super(config);

    if (config.initialValue) {
      this.initialValue = config.initialValue as TValue;
    } else {
      this.initialValue = undefined as unknown as TValue;
    }

    this.options = config.options
      .map((opt, index) => {
        let option = {} as Partial<PromptOption<TValue>>;
        if (typeof opt === "string") {
          option = {
            label: opt,
            value: opt as TValue,
            selected: false,
            disabled: false
          };
        } else if (typeof opt === "object") {
          option = opt;
        } else {
          throw new Error(
            `Invalid option provided to SelectPrompt at index #${index}`
          );
        }

        return {
          label: String(option.value) || "",
          ...option,
          description: option.description,
          selected:
            !!option.selected ||
            (this.initialValue !== undefined &&
              option.value === this.initialValue),
          disabled: !!option.disabled
        } as PromptOption<TValue>;
      })
      .sort((a, b) => a.label.localeCompare(b.label))
      .map((option, index) => ({ ...option, index }));

    const selected = this.options.findIndex(option => option.selected);
    if (selected > -1) {
      this.cursor = selected;
      if (this.options[this.cursor]) {
        this.initialValue = this.options[this.cursor].value as TValue;
      }
    }

    if (
      this.initialValue === undefined &&
      this.options.length > 0 &&
      this.options[0]
    ) {
      this.initialValue = this.options[0].value as TValue;
    }

    if (config.optionsPerPage) {
      this.optionsPerPage = config.optionsPerPage;
    }

    this.sync();
  }

  /**
   * Returns the currently selected option
   */
  protected get selectedOption(): PromptOption<TValue> | null {
    return this.options.find(option => option.value === this.value) ?? null;
  }

  /**
   * A method to route key press events to specific prompt actions based on the key pressed. This method maps various key combinations and keys to corresponding actions that can be handled by the prompt, such as submitting, cancelling, navigating, etc.
   *
   * @param key
   */
  protected override getAction(key: Key): string | false {
    let action = super.getAction(key);
    if (!action) {
      if (key.name === "j") action = "down";
      if (key.name === "k") action = "up";
    }

    return action || false;
  }

  /**
   * A method to reset the prompt input
   */
  protected override reset() {
    this.moveCursor(0);
    super.reset();
  }

  /**
   * A method to submit the prompt input
   */
  protected override async submit() {
    if (!this.selectedOption?.disabled) {
      await super.submit();
    } else {
      this.bell();
    }
  }

  /**
   * A method to move the cursor to the end of the input
   */
  protected next() {
    this.moveCursor((this.cursor + 1) % this.options.length);
    this.sync();
  }

  /**
   * A method to move the cursor to the left or right by a \`count\` of positions
   *
   * @param count
   */
  protected override moveCursor(count: number) {
    this.cursor = count;

    this.changeValue(this.options[count]!.value);
    this.sync();
  }

  /**
   * A method to move the cursor to the first option
   */
  protected first() {
    this.moveCursor(0);
    this.sync();
  }

  /**
   * A method to move the cursor to the last option
   */
  protected last() {
    this.moveCursor(this.options.length - 1);
    this.sync();
  }

  /**
   * A method to move the cursor to the start
   */
  protected first_2() {
    this.cursor = 0;
    this.sync();
  }

  /**
   * A method to move the cursor to the up
   */
  protected up() {
    if (this.cursor === 0) {
      this.moveCursor(this.options.length - 1);
    } else {
      this.moveCursor(this.cursor - 1);
    }

    this.sync();
  }

  /**
   * A method to move the cursor to the down
   */
  protected down() {
    if (this.cursor === this.options.length - 1) {
      this.moveCursor(0);
    } else {
      this.moveCursor(this.cursor + 1);
    }

    this.sync();
  }

  /**
   * A method to render the prompt
   */
  protected override onRender() {
    const spacing =
      Math.max(...this.options.map(option => option.label?.length || 0)) + 2;

    const startIndex = Math.max(
      Math.min(
        this.options.length - this.optionsPerPage,
        this.cursor - Math.floor(this.optionsPerPage / 2)
      ),
      0
    );
    const endIndex = Math.min(
      startIndex + this.optionsPerPage,
      this.options.length
    );

    let output = "";
    if (!this.isCompleted) {
      output += " \n";
      for (let index = startIndex; index < endIndex; index++) {
        output += `${
          this.options[index].disabled
            ? this.cursor === index
              ? bold(textColors.prompt.input.disabled(">"))
              : index === startIndex
                ? borderColors.app.divider.tertiary("↑")
                : index === endIndex - 1
                  ? borderColors.app.divider.tertiary("↓")
                  : " "
            : this.cursor === index
              ? bold(textColors.prompt.input.active(">"))
              : index === startIndex
                ? borderColors.app.divider.tertiary("↑")
                : index === endIndex - 1
                  ? borderColors.app.divider.tertiary("↓")
                  : " "
        } ${
          this.options[index]!.disabled
            ? this.cursor === index
              ? bold(
                  textColors.prompt.input.disabled(
                    this.options[index]!.icon
                      ? underline(`${this.options[index]!.icon}  `)
                      : ""
                  )
                )
              : strikethrough(
                  textColors.prompt.input.disabled(
                    this.options[index]!.icon
                      ? `${this.options[index].icon}  `
                      : ""
                  )
                )
            : this.cursor === index
              ? bold(
                  textColors.prompt.input.active(
                    this.options[index]!.icon
                      ? underline(`${this.options[index]!.icon}  `)
                      : ""
                  )
                )
              : textColors.prompt.input.inactive(
                  this.options[index]!.icon
                    ? `${this.options[index].icon}  `
                    : ""
                )
        }${
          this.options[index]!.disabled
            ? this.cursor === index
              ? bold(
                  underline(
                    textColors.prompt.input.disabled(this.options[index].label)
                  )
                )
              : strikethrough(
                  textColors.prompt.input.disabled(this.options[index]!.label)
                )
            : this.cursor === index
              ? bold(
                  underline(
                    textColors.prompt.input.active(this.options[index]!.label)
                  )
                )
              : textColors.prompt.input.inactive(this.options[index]!.label)
        } ${" ".repeat(Math.max(0, spacing - this.options[index]!.label.length - (this.options[index]!.icon ? this.options[index]!.icon!.length + 1 : 0)))}${
          this.options[index]!.description && this.cursor === index
            ? italic(
                textColors.prompt.description.active(
                  this.options[index]!.description
                )
              )
            : ""
        } \n`;
      }
    } else {
      this.displayValue = this.selectedOption?.label || String(this.value);
      output += super.onRender();
    }

    return output;
  }
}

