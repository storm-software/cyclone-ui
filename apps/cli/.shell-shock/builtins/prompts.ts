/**
 * A prompt for text input
 */
class StringPrompt extends Prompt<string> {
  #isInvalid: boolean = false;
  protected override initialValue: string = "";

  constructor(config: StringPromptConfig) {
    super(config);

    if (config.initialValue) {
      this.initialValue = config.initialValue;
    }

    if (this.initialValue) {
      this.changeValue(this.initialValue);
    }

    this.cursor = 0;
    this.sync();
    this.last();
  }

  /**
   * A method to handle onKeyPress events and determine the corresponding action
   *
   * @param char
   * @param key
   */
  protected override onKeyPress(char: string, key: Key) {
    const action = this.getAction(key);
    if (action && typeof (this as any)[action] === "function") {
      return (this as any)[action]();
    }

    if (!char || char.length === 0) {
      return this.bell();
    }

    this.changeValue(
      `${this.displayValue.slice(
        0,
        this.cursor
      )}${char}${this.displayValue.slice(this.cursor)}`
    );
    this.sync();
  }

  /**
   * A method to handle changes in the prompt value
   *
   * @param previousValue
   */
  protected override onChange(previousValue: string) {
    this.#isInvalid = false;
    this.cursor = this.displayValue.slice(0, this.cursor).length + 1;
  }

  /**
   * A method to reset the prompt input
   */
  protected override reset() {
    this.cursor = Number(!!this.initialValue);
    super.reset();
  }

  /**
   * A method to validate the prompt input
   */
  protected override async checkValidations() {
    await super.checkValidations(this.value);
    this.#isInvalid = this.isError;
  }

  /**
   * A method to move the cursor to the end of the input
   */
  protected next() {
    this.changeValue(this.initialValue);
    this.cursor = this.displayValue.length;
    this.sync();
  }

  /**
   * A method to move the cursor to the start
   */
  protected first() {
    this.cursor = 0;
    this.sync();
  }

  /**
   * A method to move the cursor to the end
   */
  protected last() {
    this.cursor = this.displayValue.length;
    this.sync();
  }

  /**
   * A method to move the cursor to the left
   */
  protected left() {
    if (this.cursor <= 0) {
      return this.bell();
    }

    this.moveCursor(-1);
    this.sync();
  }

  /**
   * A method to move the cursor to the right
   */
  protected right() {
    if (this.cursor >= this.displayValue.length) {
      return this.bell();
    }

    this.moveCursor(1);
    this.sync();
  }

  /**
   * A method to render the prompt
   */
  protected override onRender(): string {
    return this.isPlaceholder
      ? textColors.prompt.input.disabled(this.displayValue)
      : this.#isInvalid
        ? textColors.prompt.input.error(this.displayValue)
        : this.isSubmitted
          ? textColors.prompt.input.submitted(this.displayValue)
          : this.isCancelled
            ? textColors.prompt.input.cancelled(this.displayValue)
            : bold(textColors.prompt.input.active(this.displayValue));
  }
}

