/**
 * Configuration options for creating a boolean confirm prompt
 */
export interface ConfirmPromptConfig extends PromptConfig<boolean> {
  /**
   * The message for the \`Yes\` state of the prompt
   *
   * @defaultValue "Yes"
   */
  yesMessage?: string;

  /**
   * The \`Yes\` option when choosing between yes/no
   *
   * @defaultValue "1"
   */
  yesOption?: string;

  /**
   * The message for the \`No\` state of the prompt
   *
   * @defaultValue "(Y/n)"
   */
  noMessage?: string;

  /**
   * The \`No\` option when choosing between yes/no
   *
   * @defaultValue "(y/N)"
   */
  noOption?: string;
}

/**
 * A prompt for confirming a boolean input
 */
export class ConfirmPrompt extends Prompt<boolean> {
  protected override initialValue: boolean = false;
  protected yesMessage: string = "Yes";
  protected yesOption: string = "(Y/n)";
  protected noMessage: string = "No";
  protected noOption: string = "(y/N)";
  protected override cursorHidden: boolean = true;

  constructor(config: ConfirmPromptConfig) {
    super(config);

    if (config.initialValue) {
      this.initialValue = config.initialValue;
    }

    if (config.yesMessage) {
      this.yesMessage = config.yesMessage;
    }
    if (config.yesOption) {
      this.yesOption = config.yesOption;
    }
    if (config.noMessage) {
      this.noMessage = config.noMessage;
    }
    if (config.noOption) {
      this.noOption = config.noOption;
    }

    this.sync();
  }

  /**
   * A method to handle key press events and determine the corresponding action
   *
   * @param char
   * @param key
   */
  protected override onKeyPress(char: string, key: Key) {
    const action = this.getAction(key);
    if (action && typeof (this as any)[action] === "function") {
      return (this as any)[action]();
    }

    if (
      char.toLowerCase() === "y" ||
      char.toLowerCase() === "t" ||
      char.toLowerCase() === "0"
    ) {
      this.changeValue(true);
      return this.submit();
    } else if (
      char.toLowerCase() === "n" ||
      char.toLowerCase() === "f" ||
      char.toLowerCase() === "1"
    ) {
      this.changeValue(false);
      return this.submit();
    } else {
      return this.bell();
    }
  }

  /**
   * A method to render the prompt
   */
  protected override onRender(): string {
    return this.isSubmitted
      ? textColors.prompt.input.submitted(
          this.value ? this.yesMessage : this.noMessage
        )
      : this.isCancelled
        ? textColors.prompt.input.cancelled(
            this.value ? this.yesMessage : this.noMessage
          )
        : textColors.prompt.input.inactive(
            this.initialValue ? this.yesOption : this.noOption
          );
  }
}

