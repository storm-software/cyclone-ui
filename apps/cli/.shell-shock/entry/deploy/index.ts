export interface DeployOptions extends GlobalOptions {
  /**
   * The root directory of the project to deploy. Defaults to the current working directory if not specified.
   */
  root?: string | undefined;
}

/**
 * The Deploy (powerlines deploy) command.
 *
 * @remarks
 * Deploys the project and its generated assets/artifacts.
 *
 * @title Deploy
 *
 * @param args - The command-line arguments passed to the command.
 */
export async function handler(args: string[] = useArgs()) {
  const options = {
    ...useGlobalOptions()
  } as unknown as DeployOptions;

  for (let i = 0; i < args.slice(0).length; i++) {
    const arg: string =
      args[i].length > 3 && args[i].startsWith("--")
        ? `--${args[i].slice(2).replaceAll("-", "").toLowerCase().replaceAll("-", "").replaceAll("_", "")}`
        : args[i].length > 2 && args[i].startsWith("-")
          ? `-${args[i].slice(1).replaceAll("-", "")}`
          : args[i];
    if (
      arg
        .toLowerCase()
        .replaceAll("-", "")
        .replaceAll("_", "")
        .startsWith("root=") ||
      arg.toLowerCase().replaceAll("-", "").replaceAll("_", "") === "root" ||
      arg
        .toLowerCase()
        .replaceAll("-", "")
        .replaceAll("_", "")
        .startsWith("root=") ||
      arg.toLowerCase().replaceAll("-", "").replaceAll("_", "") === "root"
    ) {
      if (
        /^--?(root)=/.test(
          "-" + arg.toLowerCase().replaceAll("-", "").replaceAll("_", "")
        )
      ) {
        options.root = arg
          .replace(/^--?(root)=/, "")
          .trim()
          .replace(/^("|')/, "")
          .replace(/("|')$/, "");
      } else if (args.length > i + 1) {
        options.root = args[++i]
          .trim()
          .replace(/^("|')/, "")
          .replace(/("|')$/, "");
      }
    }
  }

  await showBanner();
  await executeUpdate();

  if (!isHelp()) {
    writeLine("");
    if (isDevelopment || isDebug || env.LOG_LEVEL === "debug") {
      writeLine(
        textColors.body.tertiary(
          "Debug mode is enabled. Additional debug information may be logged to the console."
        )
      );
    }
  }

  if (!isInteractive) {
    const failures: string[] = [];
  }

  if (options.help) {
    return showHelp();
  } else {
    return withCommand("deploy", ["deploy"], [options], handleDeploy);
  }
}
