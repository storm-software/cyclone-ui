"use client";

import type { ColorThemeMode } from "@cyclone-ui/state/theme";
import { ThemeApi, useThemeActions } from "@cyclone-ui/state/theme";
import { config as cycloneConfig } from "@cyclone-ui/tokens/tamagui";
import type { TamaguiProviderProps } from "@tamagui/core";
import { TamaguiProvider, Theme } from "@tamagui/core";
import type { ThemeProviderProps } from "@tamagui/next-theme";
import { NextThemeProvider, useThemeSetting } from "@tamagui/next-theme";
import { useServerInsertedHTML } from "next/navigation";
import type { PropsWithChildren } from "react";
import { useEffect, useLayoutEffect, useState } from "react";
import { StyleSheet } from "react-native";

export { useRootTheme, useThemeSetting } from "@tamagui/next-theme";
export type {
  ColorScheme,
  ThemeProviderProps,
  UseThemeProps
} from "@tamagui/next-theme";

export type CycloneUIProviderProps = PropsWithChildren<
  Omit<ThemeProviderProps, "children"> & {
    /**
     * The Tamagui config.
     *
     * @defaultValue The Cyclone UI config from `@cyclone-ui/tokens/tamagui`
     */
    config?: TamaguiProviderProps["config"];

    /**
     * Skip injecting the Tamagui theme and token CSS at runtime. Set this when
     * the app imports CSS generated by the Tamagui compiler (`outputCSS`).
     *
     * @defaultValue false
     */
    disableInjectCSS?: boolean;

    /**
     * The color mode the server rendered with. Hydration starts in this mode
     * so the initial client render matches the server HTML. Keep this fixed
     * for a shared static shell; the browser preference is applied separately.
     *
     * @defaultValue "light"
     */
    mode?: ColorThemeMode;

    /**
     * An optional client-written cookie containing the resolved mode. Reading
     * it on the server requires a dynamic boundary with Cache Components;
     * omit it when only client-side theme persistence is needed.
     */
    modeCookie?: string;
  }
>;

const ITEMS: ColorThemeMode[] = ["light", "dark"];

// Set by `withCycloneUI(config, { tailwind: true })`.
const CSS_LAYER = process.env.TAMAGUI_CSS_LAYER;

// Mirrors the Next.js theme into the Cyclone theme state so `useThemeMode`
// reports the active mode.
const SyncColorMode = ({
  mode,
  onChangeMode,
  enableColorScheme
}: {
  mode: ColorThemeMode;
  enableColorScheme: boolean;
  onChangeMode: (mode: ColorThemeMode) => void;
}) => {
  const { forcedTheme, resolvedTheme } = useThemeSetting();
  const activeMode = forcedTheme ?? resolvedTheme;
  const { changeMode } = useThemeActions();

  // Forced themes and initial stored preferences do not emit onChangeTheme.
  // Read the provider's resolved setting, rather than competing DOM classes.
  useLayoutEffect(() => {
    if (activeMode === "light" || activeMode === "dark") {
      onChangeMode(activeMode);
      // next-theme skips this write when the selected mode matches the OS,
      // leaving a previous explicit color-scheme behind after a toggle.
      if (enableColorScheme) {
        document.documentElement.style.colorScheme = activeMode;
      }
    }
  }, [activeMode, enableColorScheme, onChangeMode]);

  useEffect(() => {
    changeMode(mode);
  }, [changeMode, mode]);

  return null;
};

/**
 * The root provider for Cyclone UI components in a Next.js app.
 *
 * @remarks
 * Renders `NextThemeProvider` from `@tamagui/next-theme`, which stores the
 * light/dark/system setting and applies it before hydration, around a
 * `TamaguiProvider` and the `base` sub-theme of the active mode. It also collects
 * react-native-web styles during server rendering. Read or change the theme
 * with `useThemeSetting`.
 *
 * With `withCycloneUI(config, { tailwind: true })`, it also declares the
 * cascade layer order ahead of Tamagui's stylesheet, so Tailwind utilities
 * override the Tamagui layer whichever stylesheet the browser sees first.
 *
 * @example
 * ```tsx
 * // app/layout.tsx
 * import { CycloneUIProvider } from "@cyclone-ui/nextjs/provider";
 *
 * export default function RootLayout({ children }: { children: React.ReactNode }) {
 *   return (
 *     <html lang="en" suppressHydrationWarning>
 *       <body>
 *         <CycloneUIProvider>{children}</CycloneUIProvider>
 *       </body>
 *     </html>
 *   );
 * }
 * ```
 */
export function CycloneUIProvider({
  children,
  config = cycloneConfig,
  disableInjectCSS = false,
  skipNextHead = true,
  onChangeTheme,
  mode: serverMode = "light",
  modeCookie,
  ...props
}: CycloneUIProviderProps) {
  // Keep the first client render identical to the shell. SyncColorMode reads
  // browser preferences after hydration, without a request-time cookie read.
  const [mode, setMode] = useState<ColorThemeMode>(serverMode);

  useEffect(() => {
    if (modeCookie) {
      document.cookie = `${modeCookie}=${mode}; path=/; max-age=31536000; samesite=lax`;
    }
  }, [mode, modeCookie]);

  useServerInsertedHTML(() => {
    // `getSheet` is react-native-web only.
    const sheet = (
      StyleSheet as unknown as {
        getSheet: () => { id: string; textContent: string };
      }
    ).getSheet();

    return (
      <style
        id={sheet.id}
        // eslint-disable-next-line react-dom/no-dangerously-set-innerhtml
        dangerouslySetInnerHTML={{ __html: sheet.textContent }}
      />
    );
  });

  return (
    <NextThemeProvider
      {...props}
      skipNextHead={skipNextHead}
      onChangeTheme={name => {
        if (name === "light" || name === "dark") {
          setMode(name);
        }
        onChangeTheme?.(name);
      }}>
      <ThemeApi.Provider scope="theme" initialState={{ mode, items: ITEMS }}>
        <SyncColorMode
          mode={mode}
          onChangeMode={setMode}
          enableColorScheme={props.enableColorScheme ?? true}
        />
        {CSS_LAYER && (
          // Hoisted into <head> ahead of Tamagui's `precedence="default"`
          // stylesheet, which React renders after this one.
          <style href="cyclone-ui-layer-order" precedence="default">
            {`@layer theme, base, ${CSS_LAYER}, components, utilities;`}
          </style>
        )}
        <TamaguiProvider
          config={config}
          defaultTheme={mode}
          disableInjectCSS={disableInjectCSS}>
          {/* A relative name keeps the className (`t_base`) the same for every
              mode, so hydration matches when the client starts dark; CSS picks
              the scheme from `<html>`'s `t_<mode>` class. */}
          <Theme name="base">{children}</Theme>
        </TamaguiProvider>
      </ThemeApi.Provider>
    </NextThemeProvider>
  );
}
