"use client";

import type { ColorThemeMode } from "@cyclone-ui/state/theme";
import { ThemeApi, useThemeActions } from "@cyclone-ui/state/theme";
import { config as cycloneConfig } from "@cyclone-ui/tokens/tamagui";
import type { TamaguiProviderProps } from "@tamagui/core";
import { TamaguiProvider, Theme } from "@tamagui/core";
import type { ThemeProviderProps } from "@tamagui/next-theme";
import { NextThemeProvider, useRootTheme } from "@tamagui/next-theme";
import { useServerInsertedHTML } from "next/navigation";
import type { PropsWithChildren } from "react";
import { useEffect } from "react";
import { StyleSheet } from "react-native";

export { useRootTheme, useThemeSetting } from "@tamagui/next-theme";
export type {
  ColorScheme,
  ThemeProviderProps,
  UseThemeProps
} from "@tamagui/next-theme";

export type CycloneUIProviderProps = PropsWithChildren<
  Omit<ThemeProviderProps, "children"> & {
    /**
     * The Tamagui config.
     *
     * @defaultValue The Cyclone UI config from `@cyclone-ui/tokens/tamagui`
     */
    config?: TamaguiProviderProps["config"];

    /**
     * Skip injecting the Tamagui theme and token CSS at runtime. Set this when
     * the app imports CSS generated by the Tamagui compiler (`outputCSS`).
     *
     * @defaultValue false
     */
    disableInjectCSS?: boolean;
  }
>;

const ITEMS: ColorThemeMode[] = ["light", "dark"];

// Mirrors the Next.js theme into the Cyclone theme state so `useThemeMode`
// reports the active mode.
const SyncColorMode = ({ mode }: { mode: ColorThemeMode }) => {
  const { changeMode } = useThemeActions();

  useEffect(() => {
    changeMode(mode);
  }, [changeMode, mode]);

  return null;
};

/**
 * The root provider for Cyclone UI components in a Next.js app.
 *
 * @remarks
 * Renders `NextThemeProvider` from `@tamagui/next-theme`, which stores the
 * light/dark/system setting and applies it before hydration, around a
 * `TamaguiProvider` and the matching `<mode>_base` theme. It also collects
 * react-native-web styles during server rendering. Read or change the theme
 * with `useThemeSetting`.
 *
 * @example
 * ```tsx
 * // app/layout.tsx
 * import { CycloneUIProvider } from "@cyclone-ui/nextjs/provider";
 *
 * export default function RootLayout({ children }: { children: React.ReactNode }) {
 *   return (
 *     <html lang="en" suppressHydrationWarning>
 *       <body>
 *         <CycloneUIProvider>{children}</CycloneUIProvider>
 *       </body>
 *     </html>
 *   );
 * }
 * ```
 */
export function CycloneUIProvider({
  children,
  config = cycloneConfig,
  disableInjectCSS = false,
  skipNextHead = true,
  onChangeTheme,
  ...props
}: CycloneUIProviderProps) {
  const [mode, setMode] = useRootTheme();

  useServerInsertedHTML(() => {
    // `getSheet` is react-native-web only.
    const sheet = (
      StyleSheet as unknown as {
        getSheet: () => { id: string; textContent: string };
      }
    ).getSheet();

    return (
      <style
        id={sheet.id}
        dangerouslySetInnerHTML={{ __html: sheet.textContent }}
      />
    );
  });

  return (
    <NextThemeProvider
      {...props}
      skipNextHead={skipNextHead}
      onChangeTheme={name => {
        setMode(name as ColorThemeMode);
        onChangeTheme?.(name);
      }}>
      <ThemeApi.Provider scope="theme" initialState={{ mode, items: ITEMS }}>
        <SyncColorMode mode={mode} />
        <TamaguiProvider
          config={config}
          defaultTheme={mode}
          disableInjectCSS={disableInjectCSS}>
          <Theme name={`${mode}_base`}>{children}</Theme>
        </TamaguiProvider>
      </ThemeApi.Provider>
    </NextThemeProvider>
  );
}
