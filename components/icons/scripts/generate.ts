const toPascalCase = (name: string) =>
  name
    .split("-")
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const toCamelCase = (name: string) =>
  name.replace(/-(\w)/g, (_, char: string) => char.toUpperCase());

const round = (value: number) => Math.round(value * 1000) / 1000;

/**
 * Split an icon file name into its base name and variant, or `undefined` for the variants that are not included (`twotone` and the `-transition` icons).
 *
 * @remarks
 * A few chat icons spell their filled "off" icon `-filled-off`; those are read as `-off-filled`.
 */
function parseName(
  file: string
): { name: string; variant: IconVariant } | undefined {
  const name = file
    .slice(0, -".svg".length)
    .replace(/-filled-off$/, "-off-filled");
  if (name.split("-").includes("twotone") || name.endsWith("-transition")) {
    return undefined;
  }

  for (const variant of ["filled-loop", "filled", "loop"] as const) {
    if (name.endsWith(`-${variant}`)) {
      return { name: name.slice(0, -variant.length - 1), variant };
    }
  }

  return { name, variant: "regular" };
}

const parseTime = (value: string, file: string) => {
  const match = /^(-?[\d.]+)(ms|s)$/.exec(value);
  if (!match) {
    throw new Error(`Unsupported time "${value}" in ${file}`);
  }

  return round(Number(match[1]) / (match[2] === "ms" ? 1000 : 1));
};

const toValue = (value: string): Value =>
  /^-?(?:\d+(?:\.\d*)?|\.\d+)$/.test(value) ? Number(value) : value;

const ELEMENT_TYPES = new Set(["circle", "defs", "g", "mask", "path", "rect"]);

const ELEMENT_ATTRIBUTES = new Set([
  "cx",
  "cy",
  "d",
  "fill",
  "fill-opacity",
  "height",
  "id",
  "mask",
  "opacity",
  "r",
  "stroke",
  "stroke-dasharray",
  "stroke-dashoffset",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-width",
  "transform",
  "width",
  "x",
  "y"
]);

/**
 * Presentation props inherited from parent elements, used to resolve `to` animations and mask cut strokes.
 */
const INHERITED_PROPS = new Set([
  "fillOpacity",
  "stroke",
  "strokeDasharray",
  "strokeDashoffset",
  "strokeWidth"
]);

/**
 * The SVG initial values, used as the start of a `to` animation when nothing sets or inherits the prop.
 */
const INITIAL_VALUES: Record<string, Value> = {
  cx: 0,
  cy: 0,
  fillOpacity: 1,
  opacity: 1,
  r: 0,
  strokeDashoffset: 0,
  x: 0,
  y: 0
};

interface ParseContext {
  file: string;
  inMask: boolean;
  inherited: Record<string, Value>;
  maskIds: Map<string, string>;
  /**
   * The factor applied to stroke widths: `STROKE_SCALE`, or 1 for the `bold` variant.
   */
  strokeScale: number;
  /**
   * The inherited stroke width, before scaling.
   */
  strokeWidth?: Value;
}

/**
 * Scale a stroke width: thinner for visible lines, wider for the black strokes that cut gaps in a mask.
 */
const scaleStrokeWidth = (
  width: Value,
  stroke: Value | undefined,
  context: ParseContext
) => {
  if (typeof width !== "number") {
    throw new TypeError(
      `Unsupported stroke width "${width}" in ${context.file}`
    );
  }

  return round(
    context.inMask && stroke === "#000"
      ? width + LINE_WIDTH * (1 - context.strokeScale)
      : width * context.strokeScale
  );
};

interface Node {
  tag: string;
  attributes: Record<string, string>;
  children: Node[];
}

/**
 * Parse the markup of a line-md SVG file into a tree of nodes.
 */
function parseMarkup(svg: string, file: string): Node {
  const root: Node = { tag: "#root", attributes: {}, children: [] };
  const stack = [root];

  for (const [, closing, tag, rest, selfClosing] of svg.matchAll(
    /<(\/?)([a-z]+)\b([^>]*?)(\/?)>/gi
  )) {
    if (closing) {
      if (stack.pop()?.tag !== tag) {
        throw new Error(`Unbalanced </${tag}> in ${file}`);
      }
      continue;
    }

    const node: Node = {
      tag: tag!,
      attributes: Object.fromEntries(
        [...rest!.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, key, value]) => [
          key!,
          value!
        ])
      ),
      children: []
    };
    stack.at(-1)!.children.push(node);
    if (!selfClosing) {
      stack.push(node);
    }
  }

  const [svgNode] = root.children;
  if (root.children.length !== 1 || svgNode?.tag !== "svg") {
    throw new Error(`Expected a single <svg> element in ${file}`);
  }
  for (const [key, value] of Object.entries(svgNode.attributes)) {
    if (
      key === "viewBox"
        ? value !== "0 0 24 24"
        : !["xmlns", "width", "height"].includes(key)
    ) {
      throw new Error(`Unsupported <svg ${key}="${value}"> in ${file}`);
    }
  }

  return svgNode;
}

function parseAnimation(
  node: Node,
  element: IconElement,
  context: ParseContext
): IconAnimation {
  const { file } = context;
  const allowed =
    node.tag === "set"
      ? ["attributeName", "begin", "fill", "to"]
      : [
          "attributeName",
          "begin",
          "dur",
          "fill",
          "keyTimes",
          "repeatCount",
          "to",
          "values",
          ...(node.tag === "animateTransform" ? ["type"] : [])
        ];
  for (const key of Object.keys(node.attributes)) {
    if (!allowed.includes(key)) {
      throw new Error(
        `Unsupported "${key}" attribute on <${node.tag}> in ${file}`
      );
    }
  }

  const {
    attributeName,
    begin,
    dur,
    fill,
    keyTimes,
    repeatCount,
    to,
    values,
    type
  } = node.attributes;
  const isTransform = node.tag === "animateTransform";
  if (
    isTransform
      ? attributeName !== "transform" ||
        !["rotate", "scale", "translate"].includes(type!)
      : !attributeName
  ) {
    throw new Error(`Unsupported <${node.tag}> target in ${file}`);
  }

  const prop = toCamelCase(attributeName!);
  if (!isTransform && !ELEMENT_ATTRIBUTES.has(attributeName!)) {
    throw new Error(
      `Unsupported animated attribute "${attributeName}" in ${file}`
    );
  }
  if ((values === undefined) === (to === undefined)) {
    throw new Error(
      `Expected either "values" or "to" on <${node.tag}> in ${file}`
    );
  }

  let parsedValues = (values ?? to!)
    .split(";")
    .map(value => (isTransform ? value.trim() : toValue(value.trim())));
  if (prop === "strokeWidth") {
    const stroke = element.props?.stroke ?? context.inherited.stroke;
    parsedValues = parsedValues.map(value =>
      scaleStrokeWidth(value, stroke, context)
    );
  }

  // A `to` animation starts from the underlying value; resolve it when that value is inherited
  if (
    values === undefined &&
    node.tag !== "set" &&
    element.props?.[prop] === undefined &&
    !element.animations?.some(animation => animation.prop === prop)
  ) {
    const inherited = context.inherited[prop] ?? INITIAL_VALUES[prop];
    if (inherited === undefined) {
      throw new Error(
        `No underlying "${attributeName}" value for a "to" animation in ${file}`
      );
    }
    parsedValues = [inherited, ...parsedValues];
  }

  if (repeatCount !== undefined && repeatCount !== "indefinite") {
    throw new Error(`Unsupported repeatCount "${repeatCount}" in ${file}`);
  }
  if (fill !== undefined && fill !== "freeze" && fill !== "remove") {
    throw new Error(`Unsupported fill "${fill}" on <${node.tag}> in ${file}`);
  }
  if (node.tag !== "set" && dur === undefined) {
    throw new Error(`Missing "dur" on <${node.tag}> in ${file}`);
  }

  // Keys are added in this order so the generated data reads prop, timing, then values
  const animation = { prop } as IconAnimation;
  if (isTransform) {
    animation.transform = type as IconAnimation["transform"];
  }
  if (begin !== undefined && parseTime(begin, file) !== 0) {
    animation.begin = parseTime(begin, file);
  }
  if (dur !== undefined) {
    animation.dur = parseTime(dur, file);
  }
  animation.values = parsedValues;
  if (keyTimes !== undefined) {
    animation.keyTimes = keyTimes.split(";").map(Number);
  }
  if (repeatCount === "indefinite") {
    animation.repeat = true;
  }
  if (fill === "freeze") {
    animation.freeze = true;
  }

  return animation;
}

function parseElement(node: Node, context: ParseContext): IconElement {
  const { file } = context;
  if (!ELEMENT_TYPES.has(node.tag)) {
    throw new Error(`Unsupported <${node.tag}> element in ${file}`);
  }

  const element: IconElement = { type: node.tag as IconElement["type"] };
  const props: Record<string, Value> = {};
  for (const [key, value] of Object.entries(node.attributes)) {
    if (key === "style") {
      const match = /^transform-origin:\s*(-?[\d.]+)px\s+(-?[\d.]+)px;?$/.exec(
        value.trim()
      );
      if (!match) {
        throw new Error(`Unsupported style "${value}" in ${file}`);
      }
      element.origin = [Number(match[1]), Number(match[2])];
    } else if (!ELEMENT_ATTRIBUTES.has(key)) {
      throw new Error(
        `Unsupported "${key}" attribute on <${node.tag}> in ${file}`
      );
    } else if (key === "id") {
      const id = `m${context.maskIds.size}`;
      context.maskIds.set(value, id);
      props.id = id;
    } else if (key === "mask") {
      const id = context.maskIds.get(/^url\(#(.+)\)$/.exec(value)?.[1] ?? "");
      if (!id) {
        throw new Error(`Unknown mask "${value}" in ${file}`);
      }
      props.mask = id;
    } else {
      props[toCamelCase(key)] = key === "transform" ? value : toValue(value);
    }
  }
  const strokeWidth = props.strokeWidth ?? context.strokeWidth;
  if (props.strokeWidth !== undefined) {
    props.strokeWidth = scaleStrokeWidth(
      props.strokeWidth,
      props.stroke ?? context.inherited.stroke,
      context
    );
  } else if (
    context.inMask &&
    props.stroke === "#000" &&
    strokeWidth !== undefined
  ) {
    // A cut stroke that inherits its width from a visible-line group is widened on its own
    props.strokeWidth = scaleStrokeWidth(strokeWidth, "#000", context);
  }
  if (Object.keys(props).length > 0) {
    element.props = props;
  }

  const childContext: ParseContext = {
    ...context,
    inMask: context.inMask || node.tag === "mask",
    inherited: {
      ...context.inherited,
      ...Object.fromEntries(
        Object.entries(props).filter(([key]) => INHERITED_PROPS.has(key))
      )
    },
    strokeWidth
  };

  const children: IconElement[] = [];
  const animations: IconAnimation[] = [];
  for (const child of node.children) {
    if (["animate", "animateTransform", "set"].includes(child.tag)) {
      element.animations = animations;
      animations.push(parseAnimation(child, element, childContext));
    } else {
      children.push(parseElement(child, childContext));
    }
  }
  if (children.length > 0) {
    element.children = children;
  }
  if (animations.length > 0) {
    // Later `begin` times have priority, as in SVG; the sort is stable for equal times
    element.animations = animations.sort(
      (a, b) => (a.begin ?? 0) - (b.begin ?? 0)
    );
  } else {
    delete element.animations;
  }

  return element;
}

function parseSvg(
  svg: string,
  file: string,
  strokeScale = STROKE_SCALE
): IconElement[] {
  const context: ParseContext = {
    file,
    inMask: false,
    inherited: {},
    maskIds: new Map(),
    strokeScale
  };

  return parseMarkup(svg, file).children.map(node =>
    parseElement(node, context)
  );
}

/**
 * Serialize data as a TypeScript expression, with unquoted keys where possible.
 */
const toSource = (value: unknown): string => {
  if (Array.isArray(value)) {
    return `[${value.map(toSource).join(", ")}]`;
  }
  if (value && typeof value === "object") {
    return `{ ${Object.entries(value)
      .map(
        ([key, item]) =>
          `${/^[a-z_$][\w$]*$/i.test(key) ? key : JSON.stringify(key)}: ${toSource(item)}`
      )
      .join(", ")} }`;
  }

  return JSON.stringify(value);
};

