const VARIANTS = ["regular", "bold", "loop", "filled", "filled-loop"] as const;

type IconVariant = (typeof VARIANTS)[number];

/**
 * The factor applied to every stroke width, so the 2px line-md strokes render at 1.5px, closer to the thin lines of Material Design Light.
 *
 * @remarks
 * The `bold` variant is not scaled, so it keeps the original line-md strokes.
 *
 * @see https://github.com/Templarian/MaterialDesignLight
 */
const STROKE_SCALE = 0.75;

/**
 * Per-icon stroke factors for the `bold` variant, for icons whose original line-md strokes read too thin.
 */
const BOLD_STROKE_SCALE: Record<string, number> = {
  confirm: 2,
  minus: 2
};

/**
 * The stroke width of the visible lines in line-md.
 *
 * @remarks
 * Black mask strokes cut a gap next to a visible line (for example the slash of an `-off` icon). They are widened by the width the visible line lost, so the gap still meets the thinner line.
 */
const LINE_WIDTH = 2;

type Value = number | string;

interface IconAnimation {
  prop: string;
  transform?: "rotate" | "scale" | "translate";
  begin?: number;
  dur?: number;
  values: Value[];
  keyTimes?: number[];
  repeat?: boolean;
  freeze?: boolean;
}

interface IconElement {
  type: "circle" | "defs" | "g" | "mask" | "path" | "rect";
  props?: Record<string, Value>;
  origin?: [number, number];
  children?: IconElement[];
  animations?: IconAnimation[];
}

interface IconSpec {
  name: string;
  component: string;
  source: "line-md" | "assets";
  variants: Partial<Record<IconVariant, IconElement[]>>;
}

interface IconsSpec {
  version: string;
  icons: IconSpec[];
}

