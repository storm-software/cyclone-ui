const { Cam, circ, clamp, disposer, facing, fit, hull, mk, open, pointer, poly } = HL;
const { prism, proj, put, register, rings, rrect, seg, solid, spring, stepS, unproj } = HL;

/**
 * Missing: a stand loupe on three legs over a ruled sheet with nothing written
 * on it but a question mark, where the rules break off. The pointer drags the
 * loupe across the sheet on a spring. Under the glass the rules and the
 * question mark are drawn again, larger, and there is nothing else.
 * At rest the glass straddles the margin where the rules start, so their ends
 * land inside it well away from where the runs outside it would put them;
 * its thin rim is the bright mark. The slider is the magnification.
 *
 * The pattern: follow a position. Two springs hold the point of the sheet the
 * eye sees through the glass's centre, set from the pointer on the sheet's
 * plane, which never moves; the loupe stands where its glass covers that
 * point. The glass shows the sheet there enlarged, cut to the lens by
 * arithmetic, not by a clip. Past the sheet's near edges the feet stand on
 * the table, so the glass reaches every rule.
 */

const SW = 124, SD = 92, ST = 2.4; // the sheet: width, depth, thickness
const ROWS = 7, Y0 = 13, DY = 11, ML = 26, MR = 12; // its rules: how many, the first one's y, their pitch, left margin, right one
const R = 27, LZ = 20, RIM = 1.2, GLASS = R - 1.4; // the loupe: ring radius, height of its underside, ring depth, glass radius
const QX = 92, QY = 50, QK = 2.55 / Math.SQRT2, HW = 1.2, DOT = 1.9; // the question mark: its centre, scale over the diagonal it stands up along, half its weight, its dot's radius
const LEGS = [45, 165, 285], FOOT = 35, PAD = 1.8, REST = [ML + 9, 46], S = 2.1;

const mount = ({ stage, svg, read }, value) => {
  const bag = disposer();
  const C = Cam(45, 0.5, S),
    top = LZ + RIM;
  const feet = LEGS.map(a => [Math.cos((a * Math.PI) / 180), Math.sin((a * Math.PI) / 180)]);
  /** From the point the eye sees to the loupe's centre: the glass stands this far in front of it. */
  const [bx, by] = unproj(C, ...proj(C)(0, 0, 0), top);
  // The frame holds the rest pose; the reach still fits inside it (see the far and near corners).
  const ext = [[0, 0, -ST], [SW, 0, -ST], [0, SD, -ST], [SW, SD, -ST]];
  for (const q of circ(R, 16))
    ext.push([REST[0] + bx + q.u, REST[1] + by + q.v, top]);
  fit(C, ext, 200, 166);
  const P = proj(C),
    front = facing(C);
  const g = mk("g", {}, svg);

  // The sheet, then its rules lying on it.
  const [so, si] = rings(0, 0, SW, SD, 6, 1.4);
  put(solid(g), prism(P, front, so, si, -ST, 0));
  const rowY = i => Y0 + i * DY;
  /** The question mark, as segments in glyph space (y up), stood upright to the eye: up runs to the far corner. */
  const at2 = (gx, gy) => [QX + (gx - gy) * QK, QY - (gx + gy) * QK];
  const glyph = [];
  // its centreline, in glyph space: the hook, then the stem; drawn as a band HW either side with round ends
  const mid = [];
  for (let i = 0; i <= 14; i++) {
    const t = ((165 - (210 * i) / 14) * Math.PI) / 180;
    mid.push([5 * Math.cos(t), 5 + 5 * Math.sin(t)]);
  }
  const [h0, h1] = mid[14]; // the hook bends down into the stem along a curve leaving it on its tangent
  for (let j = 1; j <= 8; j++) {
    const t = j / 8, u = 1 - t;
    mid.push([u * u * h0, u * u * h1 + 2 * u * t * (h1 - h0) - 3.2 * t * t]);
  }
  mid.push([0, -4.7], [0, -6.2]); // then the tail drops straight
  const nrm = mid.map((p, i) => {
    const a = mid[Math.max(0, i - 1)], b = mid[Math.min(mid.length - 1, i + 1)], l = Math.hypot(b[0] - a[0], b[1] - a[1]);
    return [(a[1] - b[1]) / l, (b[0] - a[0]) / l];
  });
  const side = k => mid.map((p, i) => [p[0] + nrm[i][0] * HW * k, p[1] + nrm[i][1] * HW * k]);
  const cap = (p, n) => Array.from({ length: 7 }, (_, j) => {
    const t = (Math.PI * j) / 6, c = Math.cos(t), s = Math.sin(t);
    return [p[0] + HW * (n[0] * c + n[1] * s), p[1] + HW * (n[1] * c - n[0] * s)];
  });
  const e = mid.length - 1;
  const band = [...side(1), ...cap(mid[e], nrm[e]).slice(1, -1), ...side(-1).reverse(), ...cap(mid[0], nrm[0].map(v => -v)).slice(1, -1)];
  const dot = circ(DOT, 16).map(q => [q.u, -11.2 + q.v]);
  for (const ring of [band, dot])
    ring.forEach((p, i) => glyph.push([at2(...p), at2(...ring[(i + 1) % ring.length])]));
  const xs = glyph.flat().map(p => p[0]), ys = glyph.flat().map(p => p[1]);
  const [x0, x1, y0, y1] = [Math.min(...xs) - 4, Math.max(...xs) + 4, Math.min(...ys) - 2, Math.max(...ys) + 2];
  /** The lines on the sheet: the margin, then the rules that start at it, broken round the question mark. */
  const broken = y => y > y0 && y < y1;
  const rules = [[[ML, Y0 - 7], [ML, rowY(ROWS - 1) + 7]]];
  for (let i = 0; i < ROWS; i++) {
    const y = rowY(i);
    if (broken(y)) rules.push([[ML, y], [x0, y]], ...(x1 < SW - MR - 8 ? [[[x1, y], [SW - MR, y]]] : []));
    else rules.push([[ML, y], [SW - MR, y]]);
  }
  const lines = rules.concat(glyph);
  const path = ls =>
    ls.map(([p, q]) => seg(P(p[0], p[1], 0), P(q[0], q[1], 0))).join("");
  mk("path", { class: "nf lo", d: path(rules) }, g);
  mk("path", { class: "nf sil", d: path(glyph) }, g);

  // The loupe: three legs, a thin ring round the glass, a glint on it, the sheet seen through it.
  const legs = mk("path", { class: "nf" }, g);
  const rim = solid(g);
  const glint = mk("path", { class: "nf lo" }, g);
  const seen = mk("path", { class: "nf sil" }, g);
  const shine = circ(GLASS * 0.72, 64).slice(26, 36);
  const ring = circ(R, 64), lens = circ(GLASS, 64), edge = rrect(0, 0, SW, SD, 6, 12), pad = circ(PAD, 12);
  /** A foot on the sheet stands on its top; one past its edge, on the table under it. */
  const floor = (x, y) => (x >= 0 && x <= SW && y >= 0 && y <= SD ? 0 : -ST);

  const sx = spring(REST[0]), sy = spring(REST[1]), mag = spring(value);
  let cx = NaN, cy = NaN, dm = NaN;
  function draw() {
    if (sx.x === cx && sy.x === cy && mag.x === dm) return;
    const moved = sx.x !== cx || sy.x !== cy;
    [cx, cy, dm] = [sx.x, sy.x, mag.x];
    const dx = cx + bx, dy = cy + by;
    if (moved) {
      const at = (q, z) => P(dx + q.u, dy + q.v, z);
      const leg = ([c, s]) => {
        const fx = dx + c * FOOT, fy = dy + s * FOOT, z = floor(fx, fy);
        return seg(P(fx, fy, z), P(dx + c * (R - 1), dy + s * (R - 1), LZ)) + poly(pad.map(q => P(fx + q.u, fy + q.v, z)));
      };
      legs.setAttribute("d", feet.map(leg).join(""));
      const sil = poly(hull(ring.map(q => at(q, LZ)).concat(ring.map(q => at(q, top)))));
      put(rim, { sil, crease: poly(lens.map(q => at(q, top))) });
      glint.setAttribute("d", open(shine.map(q => at(q, top))));
    }
    // A line on the sheet, enlarged about the point the eye sees through the
    // glass's centre, and kept where it falls inside the glass.
    const r = GLASS - 1;
    const cut = (p, q) => {
      const a0 = (p[0] - cx) * dm, a1 = (p[1] - cy) * dm, e0 = (q[0] - p[0]) * dm, e1 = (q[1] - p[1]) * dm;
      const A = e0 * e0 + e1 * e1, B = a0 * e0 + a1 * e1, D = B * B - A * (a0 * a0 + a1 * a1 - r * r);
      if (D <= 0) return "";
      const t0 = Math.max(0, (-B - Math.sqrt(D)) / A), t1 = Math.min(1, (-B + Math.sqrt(D)) / A);
      const on = t => P(dx + a0 + e0 * t, dy + a1 + e1 * t, top);
      return t1 > t0 ? seg(on(t0), on(t1)) : "";
    };
    const nx = i => edge[(i + 1) % edge.length];
    let d = edge.map((q, i) => cut([q.u, q.v], [nx(i).u, nx(i).v])).join("");
    for (const [p, q] of lines) d += cut(p, q);
    seen.setAttribute("d", d);
  }

  const loop = register(stage, dt => {
    const a = stepS(sx, dt), b = stepS(sy, dt), c = stepS(mag, dt);
    draw();
    return a || b || c;
  });
  bag.add(loop.unregister);
  rim.sil.classList.add("hi");
  read.textContent = "rest";
  draw();

  bag.add(
    pointer(stage, {
      move: p => {
        // the pointer on the sheet's plane, which never moves: the glass comes to cover the point under it
        const [x, y] = unproj(C, p[0], p[1], 0);
        sx.t = clamp(x, ML, SW - MR);
        sy.t = clamp(y, Y0, rowY(ROWS - 1));
        const near = sx.t > x0 && sx.t < x1 && broken(sy.t);
        read.textContent = `row ${Math.round((sy.t - Y0) / DY) + 1} · ${near ? "?" : "0"}`;
        loop.wake();
      },
      leave: () => {
        sx.t = REST[0];
        sy.t = REST[1];
        read.textContent = "rest";
        loop.wake();
      }
    })
  );
  bag.add(() => svg.replaceChildren());

  const set = v => {
    mag.t = v;
    loop.wake();
  };
  return { set, destroy: bag.dispose };
};

